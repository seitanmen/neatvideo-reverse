"""Generate qtui/src/widgets/band_pixmaps.inc: the five 22 x 16 grey band pictures of the side panels
(repro/nv_ui_qt/widgets/rows.band_pixmap, computed with scipy / numpy there) as bytes for the C++ UI.

    QT_QPA_PLATFORM=offscreen python3 qtui/tools/gen_band_pixmaps.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "repro"))

from PySide6.QtGui import QImage  # noqa: E402
from PySide6.QtWidgets import QApplication  # noqa: E402

app = QApplication.instance() or QApplication([])
from nv_ui_qt.widgets import rows  # noqa: E402

out = ["// Generated by qtui/tools/gen_band_pixmaps.py from repro/nv_ui_qt/widgets/rows.band_pixmap",
       "// (QT_QPA_PLATFORM=offscreen python3 qtui/tools/gen_band_pixmaps.py). 22 x 16 Grayscale8, row-major.",
       "// Do not edit."]
for band in ("high", "medium", "low", "very-low", "ultra-low"):
    img = rows.band_pixmap(band).toImage().convertToFormat(QImage.Format_Grayscale8)
    w, h = img.width(), img.height()
    data = []
    for y in range(h):
        line = img.constScanLine(y)
        data.extend(bytes(line)[:w])
    name = band.replace("-", "_")
    out.append(f"static const unsigned char BAND_PM_{name}[{w * h}] = {{")
    for i in range(0, len(data), 22):
        out.append("    " + ", ".join(str(v) for v in data[i:i + 22]) + ",")
    out.append("};")
dst = os.path.join(ROOT, "qtui", "src", "widgets", "band_pixmaps.inc")
with open(dst, "w") as fh:
    fh.write("\n".join(out) + "\n")
print("wrote", dst)
